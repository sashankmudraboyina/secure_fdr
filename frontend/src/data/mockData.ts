// Helper to format currency in Indian style (₹ 25,00,000 / 25 Lakhs)
export function formatINR(amount: number): string {
  const formatted = new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
  
  // Also provide human-friendly Indian Lakhs / Crores
  let wordSuffix = '';
  if (amount >= 10000000) {
    wordSuffix = ` (${(amount / 10000000).toFixed(2)} Cr)`;
  } else if (amount >= 100000) {
    wordSuffix = ` (${(amount / 100000).toFixed(2)} Lakhs)`;
  }
  return `${formatted}${wordSuffix}`;
}

export function formatINRPlain(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

